#!/usr/bin/env python3
"""Regenerate src/free-catalog.generated.ts from a checkout of tashfeenahmed/freellmapi (MIT).

    git clone https://github.com/tashfeenahmed/freellmapi /tmp/fla
    (cd /tmp/fla && npm install && cd server && FREEAPI_DB_PATH=/tmp/fla_catalog.db npx tsx src/db/migrate/cli.ts fresh)
    python3 tools/import_freellmapi.py /tmp/fla /tmp/fla_catalog.db

Only data is imported (endpoints, model ids, published free-tier limits). Chat providers only: search, voice and media
adapters, pay-per-use gateways and the project's paid live catalog feed are not imported.
"""
import json, re, sqlite3, subprocess, sys
from pathlib import Path

repo = Path(sys.argv[1]); db_path = sys.argv[2]
out = Path(__file__).resolve().parent.parent / "src" / "free-catalog.generated.ts"
commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()

# ---- provider endpoints: every OpenAI-compatible chat gateway registered in providers/index.ts ----
index = (repo / "server/src/providers/index.ts").read_text()
compat = {m.group(1): m.group(2) for m in re.finditer(r"platform:\s*'([a-z0-9_-]+)'[\s\S]{0,260}?baseUrl:\s*'([^']+)'", index)}

# Custom adapters that speak plain OpenAI chat completions on a /v1 base (read from each adapter's source).
custom = {
    "aclide": "https://aclide.com/v1", "airforce": "https://api.airforce/v1", "apinex": "https://api.apinex.bond/v1",
    "beatapi": "https://api.beatapi.io/v1", "clod": "https://api.clod.io/v1", "electronhub": "https://api.electronhub.ai/v1",
    "experiential": "https://api.experientiallabs.ai/v1", "freeinference": "https://freeinference.org/v1",
    "freemodel": "https://freemodel.in/v1", "gizmo": "https://api.gizmoplatforms.com/api/v1",
    "iteracompute": "https://api.iteracompute.com/v1", "kenari": "https://kenari.id/v1", "kiosapi": "https://api.kiosapi.id/v1",
    "llmtr": "https://llmtr.com/v1", "logfare": "https://logfare.ai/v1", "lucidity": "https://composite.lucidity.sh/v1",
    "modelscope": "https://api-inference.modelscope.cn/v1", "nabh": "https://api.nabh.cloud/v1", "novai": "https://aiapi-pro.com/v1",
    "onomeo": "https://onomeo.com/v1", "plugsky": "https://plugsky.com/v1", "pollinations": "https://gen.pollinations.ai/v1",
    "router9": "https://api.router9.com/v1", "sail": "https://api.sailresearch.com/v1", "septor": "https://api.septorlabs.com/v1",
    "silvr": "https://api.silvrai.net/v1", "simplellm": "https://api.simplellm.eu/v1", "speka": "https://speka.me/v1",
    "typhoon": "https://api.opentyphoon.ai/v1", "waterfall": "https://api.getwaterfall.org/v1", "zro": "https://zro.moonmath.ai/v1",
}
# Not imported as chat gateways: reka (no longer free upstream), and providers handled by hand-written adapters.
skip = {"reka", "groq", "openrouter", "mistral", "cerebras", "huggingface", "nvidia", "ollama", "cohere", "google", "zhipu"}
labels = {"ovh": "OVHcloud AI Endpoints", "siliconflow": "SiliconFlow", "sealion": "SEA-LION", "longcat": "LongCat", "qianfan": "Baidu Qianfan",
          "volcengine": "Volcengine Ark", "xfyun": "iFlytek Spark", "modelscope": "ModelScope", "typhoon": "Typhoon", "requesty": "Requesty",
          "kilo": "Kilo Gateway", "opencode": "OpenCode Zen", "llm7": "LLM7", "radeon": "AMD Radeon", "pollinations": "Pollinations"}
official = {"siliconflow", "sealion", "longcat", "qianfan", "volcengine", "xfyun", "modelscope", "ovh", "typhoon", "requesty", "kilo", "opencode", "radeon"}
providers = {}
for pid, base in {**compat, **custom}.items():
    if pid in skip: continue
    providers[pid] = {"id": pid, "label": labels.get(pid, pid.replace("-", " ").replace("_", " ").title()), "base": base.rstrip("/"),
                      "tier": "official" if pid in official else "community"}

# ---- baseline model catalog: ids and published free-tier limits ----
db = sqlite3.connect(db_path); db.row_factory = sqlite3.Row
rows = db.execute("select platform, model_id, display_name, intelligence_rank, rpm_limit, rpd_limit, tpm_limit, tpd_limit, context_window, supports_vision, supports_tools from models where enabled = 1 order by platform, intelligence_rank desc").fetchall()
catalog = {}
for r in rows:
    catalog.setdefault(r["platform"], []).append({
        "id": r["model_id"], "name": r["display_name"], "rank": r["intelligence_rank"],
        **{k: r[k] for k in ("rpm_limit", "rpd_limit", "tpm_limit", "tpd_limit", "context_window") if r[k] is not None},
        "vision": bool(r["supports_vision"]), "tools": bool(r["supports_tools"]),
    })

def ts(value): return json.dumps(value, ensure_ascii=False, indent=1)
text = f"""// GENERATED by tools/import_freellmapi.py from tashfeenahmed/freellmapi @ {commit} (MIT, see THIRD_PARTY_NOTICES.md).
// Do not edit by hand. Limits are the project's published free-tier figures at that commit and are estimates.

export type CatalogModel = {{
  id: string; name: string; rank: number;
  rpm_limit?: number; rpd_limit?: number; tpm_limit?: number; tpd_limit?: number; context_window?: number;
  vision: boolean; tools: boolean;
}};
export type CommunityProvider = {{ id: string; label: string; base: string; tier: "official" | "community" }};

export const FREE_CATALOG_SOURCE = "tashfeenahmed/freellmapi@{commit}";

/** Free chat models per provider id, best first. */
export const FREE_CATALOG: Record<string, CatalogModel[]> = {ts(catalog)};

/** OpenAI-compatible chat providers beyond the hand-written adapters. Models are discovered from each provider at key-verify time. */
export const IMPORTED_PROVIDERS: CommunityProvider[] = {ts(sorted(providers.values(), key=lambda p: (p["tier"] != "official", p["id"])))};
"""
out.write_text(text)
print("catalog providers:", len(catalog), "models:", sum(len(v) for v in catalog.values()), "| imported chat providers:", len(providers))
